// Source-level regression checks. These do not replace device UI tests.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '../provider-app/src/main/java/com/zomeal/provider');
const read = name => fs.readFileSync(path.join(root, name + '.kt'), 'utf8');
for (const [file, tab] of [['ProviderDashboardScreen','Dashboard'],['ProviderDailyOrdersScreen','Orders'],['ProviderEarningsScreen','Earnings'],['ProviderProfileScreen','Profile']]) {
  assert.ok(read(file).includes(`ProviderNavigation("${tab}"`), `${tab}: shared navigation wired`);
  assert.doesNotMatch(read(file), /optDouble\("(?:rate_percent|commission_rate_percent)",\s*14\.0\)/);
}
assert.match(read('ProviderBusinessReviewPanel'), /loadApplicationStatus/);
assert.match(read('ProviderBusinessReviewPanel'), /loadApprovedServiceAreas/);
assert.match(read('ProviderBusinessReviewPanel'), /optString\("reason"\)/);
assert.match(read('ManageBusinessScreen'), /Pincode verification is not admin approval/);
assert.doesNotMatch(read('ManageBusinessScreen'), /approved or verified/);
assert.match(read('ProviderApprovedPhoto'), /requests\.accepts\(request\)/);
assert.match(read('ProviderApprovedPhoto'), /Retry photo/);
assert.match(read('SupabaseProviderRepository'), /Uploading photo \$\{index \+ 1\} of \$\{media.size\}/);
assert.match(read('ProviderEarningsScreen'), /val payout = amount < 0/);
assert.match(read('ProviderEarningsScreen'), /"REVERSAL" -> "Meal earning reversal"/);
assert.match(read('ProviderEarningsScreen'), /balanceKnown && available > 0/);
const kitchen = read('ProviderDashboardScreen');
assert.match(kitchen, /loadDailyDashboard\("LUNCH", today\)/);
assert.match(kitchen, /loadDailyDashboard\("DINNER", today\)/);
assert.match(kitchen, /KitchenPreparation\(selectedSession/);
assert.match(kitchen, /DropdownMenuItem/);
assert.doesNotMatch(kitchen, /KitchenTotal\(/);
assert.match(kitchen, /counted > active/);
assert.match(kitchen, /counted < active/);
assert.match(kitchen, /already delivered/);
assert.match(kitchen, /KitchenProgress\(selectedData, selectedSession, repository\)/);
assert.doesNotMatch(kitchen, /getSharedPreferences/);
assert.match(kitchen, /KitchenDelivery\(selectedData\)/);
assert.match(kitchen, /Exact side-item quantities are not supplied/);
assert.match(kitchen, /loadProviderProfileHub/);
assert.match(kitchen, /kitchenDishPhoto\(profile, data.optString\("date"\), label, name\)/);
assert.match(kitchen, /row.optInt\("day_of_week"\) != day/);
assert.match(kitchen, /matches.singleOrNull\(\).orEmpty\(\)/);
assert.match(kitchen, /ProviderApprovedPhoto\(repository, photo/);
assert.match(kitchen, /TOTAL MEALS/);
assert.match(kitchen, /KitchenStat\("Paused"/);
assert.match(kitchen, /KitchenStat\("Delivered"/);
assert.match(read('KitchenProgress'), /advanceKitchenStage/);
assert.match(read('KitchenProgress'), /Assign riders in Orders before dispatch/);
assert.match(read('OnboardingScreens'), /Portion per person/);
assert.match(read('ProviderDailyOrdersScreen'), /maskedCustomerPhone/);
assert.match(read('MainActivity'), /initialSlot = ordersInitialSlot/);
assert.doesNotMatch(kitchen, /MealSlotButton|Estimated earnings|Remaining capacity/);
console.log('PASS: shared navigation, approval data sources, photo retry/progress, missing-rate handling and signed ledger presentation wiring.');
