const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
(async () => {
 const db = new PGlite();
 const kitchen = '11111111-1111-1111-1111-111111111111';
 const rider = '22222222-2222-2222-2222-222222222222';
 await db.exec(`create schema auth; create role authenticated;
 create function auth.uid() returns uuid language sql as $$select '${kitchen}'::uuid$$;
 create type meal_slot as enum ('LUNCH','DINNER');
 create table provider_members(provider_id uuid,user_id uuid,is_active boolean,created_at timestamptz);
 insert into provider_members values('${kitchen}','${kitchen}',true,now());
 create table provider_delivery_personnel(id uuid,provider_id uuid,is_active boolean);
 insert into provider_delivery_personnel values('${rider}','${kitchen}',true);
 create table subscription_meals(id serial,provider_id uuid,service_date date,meal_slot meal_slot,status text,delivery_personnel_id uuid,updated_at timestamptz);
 create function provider_daily_dashboard(meal_slot,date) returns jsonb language sql as $$select '{"preview_mode":false,"is_final":true}'::jsonb$$;
 insert into subscription_meals(provider_id,service_date,meal_slot,status)
 select '${kitchen}',(now() at time zone 'Asia/Kolkata')::date,'LUNCH',s from unnest(array['SCHEDULED','SCHEDULED','PAUSED','CANCELLED','DELIVERED']) s;
 insert into subscription_meals(provider_id,service_date,meal_slot,status) values('${kitchen}',(now() at time zone 'Asia/Kolkata')::date,'DINNER','SCHEDULED');`);
 await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/202609130001_provider_kitchen_progress.sql'),'utf8'));
 const advance = stage => db.query(`select provider_advance_kitchen_stage('LUNCH',(now() at time zone 'Asia/Kolkata')::date,'${stage}') result`);
 await assert.rejects(advance('PACKING'), /Start cooking/);
 assert.equal((await advance('PREPARING')).rows[0].result.updated,2);
 await assert.rejects(advance('OUT_FOR_DELIVERY'), /Start packaging/);
 assert.equal((await advance('PACKING')).rows[0].result.updated,2);
 await assert.rejects(advance('OUT_FOR_DELIVERY'), /Assign an active rider/);
 await db.exec(`update subscription_meals set delivery_personnel_id='${rider}' where status='PACKING';`);
 assert.equal((await advance('OUT_FOR_DELIVERY')).rows[0].result.updated,2);
 await assert.rejects(advance('PREPARING'), /No eligible meals/);
 await assert.rejects(advance('DELIVERED'), /Invalid cooking stage/);
 const rows = (await db.query('select meal_slot,status from subscription_meals order by id')).rows;
 assert.deepEqual(rows.map(r=>r.status),['OUT_FOR_DELIVERY','OUT_FOR_DELIVERY','PAUSED','CANCELLED','DELIVERED','SCHEDULED']);
 await assert.rejects(db.query(`select provider_advance_kitchen_stage('LUNCH',current_date-1,'PREPARING')`), /Only today/);
 await db.exec('update provider_members set is_active=false');
 await assert.rejects(advance('PREPARING'), /Provider account required/);
 await db.exec(`update provider_members set is_active=true;
 alter table provider_delivery_personnel add column is_primary boolean default true;
 alter table provider_delivery_personnel add column created_at timestamptz default now();
 alter table subscription_meals add column delivery_address jsonb default '{}';
 alter table subscription_meals add column created_at timestamptz default now();`);
 await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/202609130002_restore_provider_route_assignment.sql'),'utf8'));
 const assigned = await db.query(`select provider_auto_assign_routes('DINNER') result`);
 assert.equal(assigned.rows[0].result.assigned,1);
 assert.equal((await db.query(`select provider_auto_assign_routes('DINNER') result`)).rows[0].result.assigned,0);
 assert.equal((await db.query(`select count(*)::int n from subscription_meals where status in ('PAUSED','CANCELLED','DELIVERED') and delivery_personnel_id is not null`)).rows[0].n,0);
 await db.close();
 console.log('PASS: sequential stages, rider requirement, protected statuses, slot isolation, date and membership checks.');
})().catch(e=>{console.error(e);process.exitCode=1});
